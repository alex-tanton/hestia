function extractPathData(svgText, label) {
  const trimmed = svgText.trim();
  if (FORBIDDEN_SVG_RE.test(trimmed)) {
    throw new Error(`Unsafe SVG markup detected for ${label}`);
  }
  const wrapperMatch = SVG_WRAPPER_RE.exec(trimmed);
  if (!wrapperMatch) {
    throw new Error(`Unexpected SVG structure for ${label}: must contain a single <path>`);
  }
  const [, svgAttrs, pathAttrs] = wrapperMatch;
  if (!VIEWBOX_RE.test(svgAttrs)) {
    throw new Error(`Unexpected viewBox for ${label}: expected "0 -960 960 960"`);
  }
  const dMatch = PATH_D_RE.exec(pathAttrs);
  if (!dMatch) {
    throw new Error(`Missing <path d="..."> attribute for ${label}`);
  }
  const pathData = dMatch[1].trim();
  if (pathData.length === 0 || !SAFE_PATH_D_RE.test(pathData)) {
    throw new Error(`Invalid SVG path data syntax for ${label}`);
  }
  return pathData;
}

async function fetchSvgPath(name, filled) {
  const suffix = filled ? '_fill1_24px.svg' : '_24px.svg';
  const url = `${BASE_URL}/${name}/materialsymbolsrounded/${name}${suffix}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: HTTP ${String(response.status)}`);
  }
  const svgText = await response.text();
  return extractPathData(svgText, `${name}${suffix}`);
}

function formatProperty(key, value) {
  const singleLine = `  ${key}: '${value}',`;
  if (singleLine.length <= 100) {
    return singleLine;
  }
  return `  ${key}:\n    '${value}',`;
}

function renderIconPathsTs(outlineEntries, filledEntries) {
  const outlineLines = outlineEntries.map(([name, d]) => formatProperty(name, d));
  const filledLines = filledEntries.map(([name, d]) => formatProperty(name, d));

  return [
    `// Generated by scripts/generate-icon-paths.mjs from google/material-design-icons@${MATERIAL_ICONS_COMMIT}.`,
    '// Do not edit by hand.',
    '',
    'export const ICON_PATHS = {',
    ...outlineLines,
    '} as const;',
    '',
    'export type IconName = keyof typeof ICON_PATHS;',
    '',
    'export const FILLED_ICON_PATHS: Partial<Record<IconName, string>> = {',
    ...filledLines,
    '};',
    '',
  ].join('\n');
}

async function fetchInBatches(items, worker, concurrency = 12) {
  const results = new Array(items.length);
  let nextIndex = 0;
  async function runWorker() {
    while (nextIndex < items.length) {
      const current = nextIndex;
      nextIndex += 1;
      results[current] = await worker(items[current]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, runWorker));
  return results;
}

async function main() {
  const outlineEntries = await fetchInBatches(OUTLINE_ICONS, async (name) => [
    name,
    await fetchSvgPath(name, false),
  ]);
  const filledEntries = await fetchInBatches(FILLED_ICONS, async (name) => [
    name,
    await fetchSvgPath(name, true),
  ]);

  const content = renderIconPathsTs(outlineEntries, filledEntries);
  const webRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
  const outPath = join(webRoot, 'src', 'components', 'ui', 'icon-paths.ts');
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, content, 'utf8');
}

await main();
